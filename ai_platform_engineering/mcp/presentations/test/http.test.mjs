import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { MongoClient } from 'mongodb';
import { SignJWT, createLocalJWKSet, exportJWK, generateKeyPair } from 'jose';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { createAuthenticator } from '../src/auth.mjs';
import { createPresentationServer } from '../src/server.mjs';
import { PresentationStore } from '../src/storage.mjs';
import { template, profile, deck } from './fixture.mjs';
test('HTTP/MCP end-to-end: private upload → discovery → plan → render → protected download, no project dependency', { skip: process.env.PRESENTATION_TEST_MONGO !== '1' }, async () => {
  const mongo = new MongoClient('mongodb://127.0.0.1:27018', { serverSelectionTimeoutMS: 2000 });
  const db = mongo.db(`presentation_test_${randomUUID().replaceAll('-', '')}`); await mongo.connect();
  const { privateKey, publicKey } = await generateKeyPair('RS256');
  const keys = createLocalJWKSet({ keys: [{ ...await exportJWK(publicKey), alg: 'RS256', kid: 'example-key' }] });
  const issuer = 'https://identity.example.test', audience = 'https://example.test/apps/presentations/mcp';
  const sign = sub => new SignJWT({ sub }).setProtectedHeader({ alg: 'RS256', kid: 'example-key' }).setIssuer(issuer).setAudience(audience).setExpirationTime('5m').sign(privateKey);
  const bearer = await sign('example-user'), stranger = await sign('other-user');
  let entitled = true;
  const authenticate = createAuthenticator({ issuer, audience, hostOrigin: 'http://host.example.test' }, { keys, fetchImpl: async () => new Response(JSON.stringify({ success: true, data: entitled ? [{ slug: 'example-team', name: 'Example', user_role: 'admin' }] : [] })) });
  const store = new PresentationStore(db, { publicUrl: 'http://127.0.0.1/apps/presentations' }); await store.initialize();
  const server = createPresentationServer({ store, authenticate, profiles: [{ id: 'example', name: 'Example', profile }], publicUrl: store.publicUrl });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  store.publicUrl = `${base}/apps/presentations`; store.downloadUrl = store.publicUrl;
  const headers = { authorization: `Bearer ${bearer}`, 'content-type': 'application/json' };
  const client = new Client({ name: 'example-agent', version: '1.0.0' });
  try {
    assert.equal((await fetch(`${base}/apps/presentations`)).status, 401);
    const ui = await fetch(`${base}/apps/presentations`, { headers });
    assert.match(await ui.text(), /Upload a template/);
    assert.match(ui.headers.get('content-security-policy'), /default-src 'none'/);
    const fixture = await (await template()).generateAsync({ type: 'nodebuffer' });
    const upload = await fetch(`${base}/apps/presentations/api/templates`, { method: 'POST', headers,
      body: JSON.stringify({ name: 'Example template', owner_team: 'example-team', profile_id: 'example', file: fixture.toString('base64') }) });
    assert.equal(upload.status, 200); const uploaded = await upload.json();
    assert.ok(uploaded.version); assert.equal(uploaded.bytes, undefined);
    await client.connect(new StreamableHTTPClientTransport(new URL(`${base}/mcp`), { requestInit: { headers } }));
    const tools = (await client.listTools()).tools.map(tool => tool.name);
    assert.deepEqual(tools.sort(), ['presentations_list_templates', 'presentations_plan', 'presentations_render']);
    const list = await client.callTool({ name: 'presentations_list_templates', arguments: {} });
    assert.equal(list.structuredContent.templates[0].id, uploaded.id);
    const input = { template_id: uploaded.id, version: uploaded.version, deck };
    const plan = await client.callTool({ name: 'presentations_plan', arguments: input });
    assert.equal(plan.structuredContent.slide_count, 3);
    const render = await client.callTool({ name: 'presentations_render', arguments: { ...input, approved: true } });
    assert.equal(render.isError, undefined); assert.equal(render.structuredContent.slide_count, 3);
    const link = render.structuredContent.download_url;
    assert.equal((await fetch(link)).status, 401);
    assert.equal((await fetch(link, { headers: { authorization: `Bearer ${stranger}` } })).status, 404);
    const download = await fetch(link, { headers });
    assert.equal(download.status, 200); assert.match(download.headers.get('content-type'), /presentationml/);
    assert.equal(Buffer.from(await download.arrayBuffer()).subarray(0, 2).toString(), 'PK');
    entitled = false;
    assert.equal((await fetch(link, { headers })).status, 404);
    const denied = await client.callTool({ name: 'presentations_render', arguments: { ...input, approved: true } });
    assert.equal(denied.isError, true);
    assert.equal((await fetch(`${base}/mcp`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' })).status, 401);
  } finally { await client.close(); await new Promise(resolve => server.close(resolve)); await db.dropDatabase(); await mongo.close(); }
});
